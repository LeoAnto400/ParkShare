"""Generate static browser configuration; no server or external dependencies."""
import json
import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]


def read_config(path):
    if not path.exists():
        raise ValueError('Copy .env.example to .env first.')
    values = {}
    allowed = {'DATA_SOURCE', 'SUPABASE_URL', 'SUPABASE_PUBLISHABLE_KEY'}
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        key, separator, value = line.partition('=')
        key = key.strip()
        if not separator or key not in allowed or key in values:
            raise ValueError('Use each of the three settings in .env.example once; do not add secrets.')
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    if values.keys() != allowed:
        raise ValueError('Include all three settings from .env.example.')
    if values['DATA_SOURCE'] not in ('demo', 'supabase'):
        raise ValueError('DATA_SOURCE must be demo or supabase.')
    key = values['SUPABASE_PUBLISHABLE_KEY']
    placeholder = key == 'YOUR_NEW_PARKSHARE_PUBLISHABLE_KEY'
    if not re.fullmatch(r'sb_publishable_[A-Za-z0-9_-]+', key) and not (placeholder and values['DATA_SOURCE'] == 'demo'):
        raise ValueError('Use only an sb_publishable_ key. Secret keys, legacy JWTs, and passwords are not allowed.')
    if values['DATA_SOURCE'] == 'supabase':
        url = urlparse(values['SUPABASE_URL'])
        if (url.scheme != 'https' or not re.fullmatch(r'[a-z0-9]+\.supabase\.co', url.netloc)
                or url.path not in ('', '/') or url.query or url.fragment):
            raise ValueError('Use the NEW project root HTTPS URL ending in .supabase.co.')
    return values


def main():
    try:
        values = read_config(ROOT / '.env')
    except ValueError as error:
        raise SystemExit(str(error)) from None
    source = '// Generated by scripts/configure.py. Browser-visible public configuration.\n'
    source += ''.join(f'export const {key} = {json.dumps(value)};\n' for key, value in values.items())
    (ROOT / 'js' / 'config.js').write_text(source, encoding='utf-8')
    print('Generated js/config.js. Restart or hard-refresh the page after configuration changes.')


if __name__ == '__main__':
    main()
